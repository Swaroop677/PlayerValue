"""
Database seeding script.

Creates all tables and populates them with synthetic football data
generated by the ml/generate_data module.

Usage:
    python scripts/seed_database.py
"""
import sys
import os

# Add project root to path so we can import backend and ml modules
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from backend.database.database import engine, SessionLocal
from backend.database.models import (
    Base, League, Club, Player, PlayerClubHistory,
    SeasonStats, MarketValue, Transfer
)
from ml.generate_data import generate_data


def clear_data(session):
    """Delete all existing data in reverse dependency order."""
    print("Clearing existing data...")
    session.query(Transfer).delete()
    session.query(MarketValue).delete()
    session.query(SeasonStats).delete()
    session.query(PlayerClubHistory).delete()
    session.query(Player).delete()
    session.query(Club).delete()
    session.query(League).delete()
    session.commit()


def seed():
    """Generate synthetic data and insert it into the database."""
    print("Creating tables if they don't exist...")
    Base.metadata.create_all(bind=engine)

    session = SessionLocal()
    try:
        clear_data(session)

        print("Generating synthetic data...")
        data = generate_data()

        # ── Leagues ───────────────────────────────────────────────────
        print("Inserting Leagues...")
        db_leagues = {}
        for league_data in data["leagues"]:
            league = League(
                name=league_data["name"],
                country=league_data["country"],
                strength_rating=league_data["strength"],
            )
            session.add(league)
            db_leagues[league_data["name"]] = league
        session.flush()  # Assigns IDs

        # ── Clubs ─────────────────────────────────────────────────────
        print("Inserting Clubs...")
        db_clubs = {}
        for club_data in data["clubs"]:
            club = Club(
                name=club_data["name"],
                country=next(
                    l["country"] for l in data["leagues"]
                    if l["name"] == club_data["league_name"]
                ),
                league_id=db_leagues[club_data["league_name"]].id,
            )
            session.add(club)
            db_clubs[club_data["name"]] = club
        session.flush()

        # ── Players ───────────────────────────────────────────────────
        print("Inserting Players...")
        db_players = {}
        for player_data in data["players"]:
            player = Player(
                name=player_data["name"],
                date_of_birth=player_data["date_of_birth"],
                nationality=player_data["nationality"],
                height_cm=int(player_data["height_cm"]),
                preferred_foot=player_data["preferred_foot"],
                primary_position=player_data["position"],
            )
            session.add(player)
            db_players[player_data["name"]] = player
        session.flush()

        # ── Player Club Histories ─────────────────────────────────────
        print("Inserting Player Club Histories...")
        # Track the latest season per player to set is_current
        latest_season_per_player = {}
        for h in data["player_club_histories"]:
            pname = h["player_name"]
            if pname not in latest_season_per_player or h["season"] > latest_season_per_player[pname]:
                latest_season_per_player[pname] = h["season"]

        histories = []
        for h in data["player_club_histories"]:
            is_current = (h["season"] == latest_season_per_player[h["player_name"]])
            history = PlayerClubHistory(
                player_id=db_players[h["player_name"]].id,
                club_id=db_clubs[h["club_name"]].id,
                season=h["season"],
                is_current=is_current,
            )
            histories.append(history)
        session.add_all(histories)

        # ── Season Stats ──────────────────────────────────────────────
        print("Inserting Season Stats...")
        stats_list = []
        for s in data["season_stats"]:
            minutes = s["minutes_played"]
            games = minutes // 90 if minutes >= 90 else 0

            stat = SeasonStats(
                player_id=db_players[s["player_name"]].id,
                club_id=db_clubs[s["club_name"]].id,
                season=s["season"],
                appearances=games,
                minutes=minutes,
                goals=s["goals"],
                assists=s["assists"],
                xg=round(s["xg"], 2),
                xa=round(s["xa"], 2),
                shots=round(s["shots"], 1),
                key_passes=round(s.get("key_passes", 0), 1),
                progressive_passes=round(s["progressive_passes"], 1),
                progressive_carries=round(s["progressive_carries"], 1),
                tackles=round(s["tackles"], 1),
                interceptions=round(s["interceptions"], 1),
                aerial_wins=round(s.get("aerial_wins", 0), 1),
                recoveries=round(s.get("recoveries", 0), 1),
                clean_sheets=s["clean_sheets"],
            )
            stats_list.append(stat)
        session.add_all(stats_list)

        # ── Market Values ─────────────────────────────────────────────
        print("Inserting Market Values...")
        values = []
        for v in data["market_values"]:
            mv = MarketValue(
                player_id=db_players[v["player_name"]].id,
                valuation_date=v["date"],
                market_value_eur=v["market_value_eur"],
            )
            values.append(mv)
        session.add_all(values)

        # ── Transfers ─────────────────────────────────────────────────
        print("Inserting Transfers...")
        transfers = []
        for t in data["transfers"]:
            transfer = Transfer(
                player_id=db_players[t["player_name"]].id,
                from_club_id=db_clubs[t["from_club_name"]].id,
                to_club_id=db_clubs[t["to_club_name"]].id,
                transfer_date=t["transfer_date"],
                fee_eur=t["fee_eur"],
                transfer_type="Transfer",
            )
            transfers.append(transfer)
        session.add_all(transfers)

        # ── Commit ────────────────────────────────────────────────────
        session.commit()

        print("\n✅ Database seeded successfully!")
        print(f"\nSummary:")
        print(f"  Leagues:            {len(db_leagues)}")
        print(f"  Clubs:              {len(db_clubs)}")
        print(f"  Players:            {len(db_players)}")
        print(f"  Club Histories:     {len(histories)}")
        print(f"  Season Stats:       {len(stats_list)}")
        print(f"  Market Values:      {len(values)}")
        print(f"  Transfers:          {len(transfers)}")

    except Exception as e:
        print(f"\n❌ Error seeding database: {e}")
        import traceback
        traceback.print_exc()
        session.rollback()
    finally:
        session.close()


if __name__ == "__main__":
    seed()
